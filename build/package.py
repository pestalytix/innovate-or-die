#!/usr/bin/env python3
"""Build the release zips from a committed tree.

    python3 build/package.py                 # from HEAD into dist/
    python3 build/package.py --ref v2.1.0    # from a tag
    python3 build/package.py --check         # build in a temp dir, assert, discard

Two assets, because two hosts disagree about where `SKILL.md` belongs and the
disagreement is not negotiable at either end:

    innovate-or-die-skill-v<ver>.zip        innovate-or-die/SKILL.md  (depth 1)
    innovate-or-die-skill-flat-v<ver>.zip   SKILL.md                  (zip root)

claude.ai requires the skill *folder* to be the zip root; Perplexity's Computer
skill upload requires `SKILL.md` itself at the zip root. Sources and quotes are
in docs/COMPATIBILITY.md. Shipping one zip and hoping means one of the two
install paths is broken, silently, for whoever tries it second.

Everything is read through `git archive` from the named ref. The working tree is
never packaged: a release asset built from uncommitted edits is a build nobody
can reproduce from the tag, and the mismatch surfaces only after the asset is
published. This is also why the layout assertions below run against the finished
zip rather than against the directory it was made from -- what ships is what gets
checked.

Drift between `core/` and the packaged tree is `build/assemble.py --check`'s job,
not this script's. The release workflow runs it first, and it must stay that way:
this script would happily package a stale `skills/` tree.

Stdlib only, like the rest of build/.
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
import tempfile
import time
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DIST = ROOT / "dist"

# The canonical Agent Skills package, as generated by build/assemble.py. Both
# assets carry exactly this tree; only the prefix differs.
PKG_DIR = "skills/innovate-or-die"

# Asserted member-for-member against each built zip. A file added to the skill
# package without being added here is a file that silently stops shipping.
EXPECTED = {
    "SKILL.md",
    "principles.md",
    "references/experiment-spec.md",
    "references/lenses.md",
    "roles/critic.md",
    "roles/evaluator.md",
    "roles/innovator.md",
    "roles/reviser.md",
}


def git(*args: str) -> bytes:
    return subprocess.run(("git", "-C", str(ROOT)) + args,
                          check=True, capture_output=True).stdout


def resolve(ref: str) -> tuple[str, str, tuple]:
    """Return (commit sha, skill version, zip timestamp) for `ref`.

    All three are read from the ref, never off disk. Naming an asset from a
    working-tree version while packaging a tag's content is how you publish
    innovate-or-die-skill-v2.2.0.zip containing v2.1.0.
    """
    # ^{commit} because `git rev-parse v2.1.0` on an ANNOTATED tag returns the
    # tag object's sha, not the commit's -- so the build log would print an id
    # that appears in no `git log` output and matches nothing anyone can check.
    sha = git("rev-parse", f"{ref}^{{commit}}").decode().strip()
    meta = json.loads(git("show", f"{ref}:core/skill-meta.json"))
    # The commit time, in UTC, becomes every member's mtime -- see restamp().
    commit_epoch = int(git("log", "-1", "--format=%ct", ref).decode().strip())
    y, mo, d, h, mi, sec = time.gmtime(commit_epoch)[:6]
    # A zip's DOS timestamp field has two-second resolution, so an odd second is
    # rounded down on write. Round here instead, so the value this function
    # returns is the value that comes back out of the built zip -- otherwise
    # every caller comparing the two sees a one-second discrepancy and has to
    # know why.
    return sha, meta["version"], (y, mo, d, h, mi, sec - sec % 2)


def archive(ref: str, out: Path, prefix: str | None) -> None:
    args = ["archive", "--format=zip", f"--output={out}"]
    if prefix:
        args.append(f"--prefix={prefix}/")
    # A `<ref>:<path>` argument resolves to a TREE, and a tree carries no date --
    # so git stamps every member with the wall-clock time of the build. Two
    # builds of the same tag then differ in bytes. restamp() undoes this.
    args.append(f"{ref}:{PKG_DIR}")
    git(*args)


def restamp(out: Path, when: tuple) -> None:
    """Rewrite every member's mtime to the commit time, in UTC.

    Without this the asset is not reproducible: the same tag packaged twice, or
    packaged in CI (UTC) versus on a laptop (not UTC), yields different bytes,
    and a published checksum stops being checkable against a rebuild. Names,
    order, contents, CRCs, compression and permission bits all pass through
    untouched -- only the timestamp is normalised.
    """
    with zipfile.ZipFile(out) as z:
        members = [(i, z.read(i.filename)) for i in z.infolist()]
    with zipfile.ZipFile(out, "w") as z:
        for info, data in members:
            info.date_time = when
            # git archive also writes an `UT` extended-timestamp extra field
            # holding a second Unix mtime -- set to build time, and invisible to
            # a `unzip -l` listing. Normalising only date_time leaves it, and the
            # zip still differs byte-for-byte between builds. The DOS field set
            # above is the one every unpacker reads; drop the shadow copy rather
            # than maintain two timestamps that can disagree.
            info.extra = b""
            z.writestr(info, data)


def assert_layout(path: Path, prefix: str | None) -> None:
    """Fail loudly if the built zip is not the layout its host demands.

    The failure this guards against is not a crash -- it is an upload that the
    host rejects with a generic error, or worse accepts and half-loads. Neither
    tells you the zip root was wrong.
    """
    with zipfile.ZipFile(path) as z:
        names = z.namelist()
        bad = z.testzip()
    if bad is not None:
        raise SystemExit(f"{path.name}: corrupt member {bad!r}")

    # git archive emits directory entries; they are structure, not content.
    members = sorted(n for n in names if not n.endswith("/"))
    want_skill = f"{prefix}/SKILL.md" if prefix else "SKILL.md"

    if want_skill not in members:
        raise SystemExit(
            f"{path.name}: SKILL.md is not at {want_skill!r}. Members: {members}")

    if prefix:
        stray = [n for n in names if not n.startswith(f"{prefix}/")]
        if stray:
            raise SystemExit(
                f"{path.name}: entries outside the {prefix}/ root: {stray}")
        # "SKILL.md at depth 1" is the actual claude.ai requirement, so assert
        # the depth rather than merely the prefix.
        if want_skill.count("/") != 1:
            raise SystemExit(f"{path.name}: SKILL.md is at depth "
                             f"{want_skill.count('/')}, expected 1")
        got = {n[len(prefix) + 1:] for n in members}
    else:
        # Perplexity: SKILL.md at the zip root, with roles/ references/ and
        # principles.md as its siblings. Anything at the root that is not a
        # sibling of SKILL.md means the tree was wrapped after all.
        got = set(members)
        for sibling in ("principles.md", "roles/", "references/"):
            if not any(n == sibling or n.startswith(sibling) for n in members):
                raise SystemExit(f"{path.name}: {sibling} missing from the zip root")

    if got != EXPECTED:
        missing = sorted(EXPECTED - got)
        extra = sorted(got - EXPECTED)
        raise SystemExit(f"{path.name}: member set does not match the expected "
                         f"skill package. missing={missing} unexpected={extra}")


def listing(path: Path) -> str:
    with zipfile.ZipFile(path) as z:
        rows = [f"  {i.file_size:>7,}  {i.filename}" for i in z.infolist()]
    return "\n".join(rows)


def main() -> int:
    ap = argparse.ArgumentParser(description="Build the release skill zips.")
    ap.add_argument("--ref", default="HEAD",
                    help="git ref to package (default: HEAD). Never the working tree.")
    ap.add_argument("--check", action="store_true",
                    help="build into a temp dir and assert; dist/ is not touched")
    args = ap.parse_args()

    sha, version, when = resolve(args.ref)

    # A dirty tree is not an error -- we package the ref, not the tree -- but it
    # is worth saying out loud, because the obvious assumption when you run this
    # after an edit is that the edit is in the zip. It is not.
    if git("status", "--porcelain").strip() and args.ref == "HEAD":
        print("note: working tree has uncommitted changes; packaging HEAD, not the tree.")

    # --check builds somewhere else entirely. It used to build into dist/ and
    # delete afterwards, which quietly removed assets a previous real run had
    # put there -- so "I built the zips" and "the zips are on disk" could both
    # be true at different moments and false together. A verification mode must
    # not be able to destroy the thing it verifies.
    out_dir = Path(tempfile.mkdtemp(prefix="package-check-")) if args.check else DIST
    out_dir.mkdir(exist_ok=True)
    built = []
    for prefix, name in (("innovate-or-die", f"innovate-or-die-skill-v{version}.zip"),
                         (None, f"innovate-or-die-skill-flat-v{version}.zip")):
        out = out_dir / name
        archive(args.ref, out, prefix)
        restamp(out, when)
        assert_layout(out, prefix)
        built.append((out, prefix))

    stamp = "%04d-%02d-%02dT%02d:%02d:%02dZ" % when
    print(f"packaged {args.ref} ({sha[:12]}) as v{version}, members stamped {stamp}\n")
    for out, prefix in built:
        root = f"{prefix}/SKILL.md" if prefix else "SKILL.md"
        shown = out.name if args.check else out.relative_to(ROOT)
        print(f"{shown}  ({out.stat().st_size:,} bytes)  -- SKILL.md at {root}")
        print(listing(out))
        print()

    if args.check:
        shutil.rmtree(out_dir, ignore_errors=True)
        print(f"--check: both layouts asserted. Built in a temp dir and discarded; "
              f"{DIST.relative_to(ROOT)}/ untouched.")
    else:
        print(f"-> {DIST.relative_to(ROOT)}/ now holds {len(built)} assets. "
              "`--check` does NOT leave them there; run without it to keep them.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
